import express from 'express';
import rateLimit from 'express-rate-limit';
import authenticate from '../middlewares/identity-auth.middleware.js';
import Controller from '../controllers/messaging.controller.js';
import errors from '../errors/registry.js';
import uploadMedia from '../middlewares/upload-media.middleware.js';
import Actions from '../controllers/chat-actions.controller.js';
const router=express.Router();
router.use(authenticate);
router.get('/moderation/reports/:report_id/messages/:message_id/media/:media_index',(req,res,next)=>Controller.reviewMedia(req,res,next));
router.get('/conversations/:conversation_id/messages/:message_id/report-context',(req,res,next)=>Controller.reportContext(req,res,next));
const sendLimit=rateLimit({windowMs:60000,limit:60,standardHeaders:true,legacyHeaders:false,keyGenerator:req=>String(req.auth.id),handler:(req,res,next)=>next(new errors.TooManyRequestsException('Please slow down and try again'))});
router.get('/conversations',(req,res,next)=>Controller.inbox(req,res,next));
router.post('/conversations',sendLimit,(req,res,next)=>Controller.start(req,res,next));
router.get('/conversations/:conversation_id/messages',(req,res,next)=>Controller.messages(req,res,next));
router.post('/conversations/:conversation_id/messages/sync',(req,res,next)=>Actions.sync(req,res,next));
router.delete('/conversations/:conversation_id/messages/:message_id',sendLimit,(req,res,next)=>Actions.remove(req,res,next));
router.put('/conversations/:conversation_id/messages/:message_id/reaction',sendLimit,(req,res,next)=>Actions.react(req,res,next));
router.delete('/conversations/:conversation_id/messages/:message_id/reaction',sendLimit,(req,res,next)=>Actions.unreact(req,res,next));
router.post('/conversations/:conversation_id/messages/:message_id/forward',sendLimit,(req,res,next)=>Actions.forward(req,res,next));
router.post('/conversations/:conversation_id/messages',sendLimit,(req,res,next)=>Controller.authorize(req,res,next),uploadMedia,(req,res,next)=>Controller.send(req,res,next));
router.get('/conversations/:conversation_id/messages/:message_id/media/:media_index',(req,res,next)=>Controller.media(req,res,next));
router.get('/conversations/:conversation_id/messages/:message_id/post',(req,res,next)=>Controller.sharedPost(req,res,next));
router.patch('/conversations/:conversation_id/read',(req,res,next)=>Controller.read(req,res,next));
export default router;
